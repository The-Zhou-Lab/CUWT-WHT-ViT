def extract_color_features(mask, original_image):
    """Extract color features from the mask region in multiple color spaces.

    Features include:
      - RGB channel means and stds
      - LAB channel means and stds (recommended for plant classification)
      - HSV key features (hue, saturation, value)
      - Hull color ratios: red, amber, white (key indicators for variety classification)

    Args:
        mask: Binary mask image (uint8, 0/255).
        original_image: Original color image (BGR).

    Returns:
        Dict of color features.
    """
    default_features = {
        'color_r_mean': 0.0, 'color_g_mean': 0.0, 'color_b_mean': 0.0,
        'color_r_std': 0.0, 'color_g_std': 0.0, 'color_b_std': 0.0,
        'color_lab_l_mean': 0.0, 'color_lab_a_mean': 0.0, 'color_lab_b_mean': 0.0,
        'color_lab_l_std': 0.0, 'color_lab_a_std': 0.0, 'color_lab_b_std': 0.0,
        'color_h_mean': 0.0, 'color_s_mean': 0.0, 'color_v_mean': 0.0,
        'color_h_std': 0.0,
        'color_red_ratio': 0.0, 'color_white_ratio': 0.0, 'color_amber_ratio': 0.0
    }

    if mask is None or original_image is None:
        return default_features

    mask_bool = mask > 0
    roi = cv2.bitwise_and(original_image, original_image, mask=mask)

    if np.sum(mask_bool) == 0:
        return default_features

    try:
        features = {}

        # RGB
        b, g, r = cv2.split(roi)
        r_values = r[mask_bool]
        g_values = g[mask_bool]
        b_values = b[mask_bool]

        features['color_r_mean'] = np.mean(r_values)
        features['color_g_mean'] = np.mean(g_values)
        features['color_b_mean'] = np.mean(b_values)
        features['color_r_std'] = np.std(r_values)
        features['color_g_std'] = np.std(g_values)
        features['color_b_std'] = np.std(b_values)

        # LAB
        lab = cv2.cvtColor(roi, cv2.COLOR_BGR2LAB)
        l, a, b_channel = cv2.split(lab)
        l_values = l[mask_bool]
        a_values = a[mask_bool]
        lab_b_values = b_channel[mask_bool]

        features['color_lab_l_mean'] = np.mean(l_values)
        features['color_lab_a_mean'] = np.mean(a_values)
        features['color_lab_b_mean'] = np.mean(lab_b_values)
        features['color_lab_l_std'] = np.std(l_values)
        features['color_lab_a_std'] = np.std(a_values)
        features['color_lab_b_std'] = np.std(lab_b_values)

        # HSV
        hsv = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV)
        h, s, v = cv2.split(hsv)
        h_values = h[mask_bool]
        s_values = s[mask_bool]
        v_values = v[mask_bool]

        features['color_h_mean'] = np.mean(h_values)
        features['color_s_mean'] = np.mean(s_values)
        features['color_v_mean'] = np.mean(v_values)
        features['color_h_std'] = np.std(h_values)

        # Hull color ratios
        total_pixels = np.sum(mask_bool)

        # Red hull range
        red_mask1 = cv2.inRange(hsv, np.array([0, 30, 50]), np.array([20, 255, 255]))
        red_mask2 = cv2.inRange(hsv, np.array([160, 30, 50]), np.array([180, 255, 255]))
        red_mask = cv2.bitwise_or(red_mask1, red_mask2)
        features['color_red_ratio'] = np.sum(red_mask[mask_bool]) / (255.0 * total_pixels)

        # Amber/golden range
        amber_mask = cv2.inRange(hsv, np.array([20, 50, 150]), np.array([40, 255, 255]))
        features['color_amber_ratio'] = np.sum(amber_mask[mask_bool]) / (255.0 * total_pixels)

        # White/pale range
        white_mask = cv2.inRange(hsv, np.array([0, 0, 160]), np.array([60, 80, 255]))
        features['color_white_ratio'] = np.sum(white_mask[mask_bool]) / (255.0 * total_pixels)

        return features

    except Exception as e:
        print(f"Color feature extraction error: {str(e)}")
        return default_features


