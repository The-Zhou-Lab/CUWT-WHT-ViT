def optimize_image_size(image, mask, max_size=1500):
    """Downsample large images to reduce memory usage.

    Args:
        image: Original image (H, W, C) or (H, W).
        mask: Corresponding mask image.
        max_size: Maximum dimension (width or height) before downsampling.

    Returns:
        (optimized_image, optimized_mask, scale_factor)
    """
    if image is None or mask is None:
        return image, mask, 1.0

    height, width = image.shape[:2]
    max_dim = max(height, width)

    if max_dim > max_size:
        scale_factor = max_size / max_dim
        new_width = int(width * scale_factor)
        new_height = int(height * scale_factor)

        optimized_image = cv2.resize(image, (new_width, new_height),
                                     interpolation=cv2.INTER_AREA)
        optimized_mask = cv2.resize(mask, (new_width, new_height),
                                    interpolation=cv2.INTER_NEAREST)
        return optimized_image, optimized_mask, scale_factor

    return image, mask, 1.0


