def filter_by_iqr(group, feature, threshold=1.5, remove_outliers=True):
    """IQR-based outlier detection for a single feature within a group.

    Args:
        group: DataFrame subset (typically one variety).
        feature: Column name to filter on.
        threshold: IQR multiplier for bounds.
        remove_outliers: If True, return cleaned data; if False, return outliers.

    Returns:
        Filtered DataFrame or outlier DataFrame.
    """
    if len(group) < 4:
        return group if remove_outliers else pd.DataFrame()

    Q1 = group[feature].quantile(0.25)
    Q3 = group[feature].quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - threshold * IQR
    upper_bound = Q3 + threshold * IQR

    is_outlier = (group[feature] < lower_bound) | (group[feature] > upper_bound)

    if remove_outliers:
        return group[~is_outlier]
    else:
        return group[is_outlier]


def calculate_quality_score(df, weights=None):
    """Compute a composite quality score for each mask, grouped by variety.

    Features and default weights:
        convex_compactness (0.30), aspect_ratio (0.15), area_px (0.10),
        spikelet_density (0.15), spikelet_count (0.10), morans_i (0.05),
        glcm_homogeneity (0.05), glcm_correlation (0.05), glcm_contrast (-0.05)

    UK varieties receive adjusted weights: lower aspect_ratio (0.05),
    higher convex_compactness (0.40), higher spikelet_density (0.20).

    Args:
        df: DataFrame with trait columns and 'variety' column.
        weights: Optional custom weight dict.

    Returns:
        DataFrame with added 'quality_score' column.
    """
    default_weights = {
        'convex_compactness': 0.30,
        'aspect_ratio': 0.15,
        'area_px': 0.10,
        'spikelet_density': 0.15,
        'spikelet_count': 0.10,
        'morans_i': 0.05,
        'glcm_homogeneity': 0.05,
        'glcm_correlation': 0.05,
        'glcm_contrast': -0.05,
    }

    uk_weights = default_weights.copy()
    uk_weights.update({
        'aspect_ratio': 0.05,
        'convex_compactness': 0.40,
        'spikelet_density': 0.20,
    })

    weights = weights or default_weights
    result_df = df.copy()
    result_df['quality_score'] = 0

    for variety, group in result_df.groupby('variety'):
        variety_weights = uk_weights if 'UK' in variety else weights
        feature_scores = {}

        for feature, weight in variety_weights.items():
            if feature in group.columns and not group[feature].isna().all():
                min_val = group[feature].min()
                max_val = group[feature].max()
                if max_val > min_val:
                    if weight > 0:
                        feature_scores[feature] = (group[feature] - min_val) / (max_val - min_val)
                    else:
                        feature_scores[feature] = 1 - (group[feature] - min_val) / (max_val - min_val)
                else:
                    feature_scores[feature] = pd.Series(0.5, index=group.index)

                result_df.loc[group.index, 'quality_score'] += abs(weight) * feature_scores[feature]

        max_possible_score = sum(abs(w) for f, w in variety_weights.items() if f in feature_scores)
        if max_possible_score > 0:
            result_df.loc[group.index, 'quality_score'] = \
                result_df.loc[group.index, 'quality_score'] / max_possible_score

    return result_df


def filter_by_multiple_features(df, features, threshold=1.5, min_group_size=5):
    """Apply IQR filtering across multiple features simultaneously.

    Args:
        df: DataFrame with trait data.
        features: List of feature column names.
        threshold: IQR multiplier.
        min_group_size: Minimum samples per variety to apply filtering.

    Returns:
        (filtered_df, outliers_df, stats_dict)
    """
    if df is None or len(df) == 0:
        return None, None, {}

    filtered_df = df.copy()
    all_outliers = []
    stats = {'total': len(df), 'filtered': 0, 'feature_outliers': {}}

    for variety, group in df.groupby('variety'):
        if len(group) < min_group_size:
            continue

        variety_outliers_by_feature = {}

        for feature in features:
            if feature not in df.columns:
                continue
            outliers = filter_by_iqr(group, feature, threshold, remove_outliers=False)
            if len(outliers) > 0:
                variety_outliers_by_feature[feature] = set(outliers.index)
                stats['feature_outliers'][feature] = stats['feature_outliers'].get(feature, 0) + len(outliers)

        all_feature_outliers = set()
        for fo in variety_outliers_by_feature.values():
            all_feature_outliers.update(fo)

        if all_feature_outliers:
            outliers_in_variety = df.loc[list(all_feature_outliers)].copy()
            outliers_in_variety['outlier_reason'] = 'multiple_features'
            all_outliers.append(outliers_in_variety)
            filtered_df = filtered_df.drop(list(all_feature_outliers))

    outliers_df = pd.concat(all_outliers) if all_outliers else pd.DataFrame()

    stats['filtered'] = len(df) - len(filtered_df)
    stats['remaining'] = len(filtered_df)
    stats['percent_filtered'] = (stats['filtered'] / stats['total']) * 100 if stats['total'] > 0 else 0

    return filtered_df, outliers_df, stats


def filter_by_threshold(df, criteria=None):
    """Apply variety-adaptive dynamic threshold filtering.

    Uses different threshold strategies based on sample size:
      - <30 samples: very loose thresholds
      - 30-50 samples: moderate thresholds
      - UK varieties: relaxed thresholds
      - Other varieties with sufficient data: standard thresholds

    Args:
        df: DataFrame with trait data.
        criteria: Optional dict of {feature: (min_val, max_val)}.

    Returns:
        (filtered_df, outliers_df, stats_dict)
    """
    if df is None or len(df) == 0:
        return None, None, {}

    filtered_df = df.copy()
    all_outliers = []
    stats = {'total': len(df), 'filtered': 0, 'threshold_outliers': {}}

    features_to_check = {
        'convex_compactness': (0.45, None),
        'ellipse_compactness': (0.4, None),
    }

    for variety, group in df.groupby('variety'):
        total_samples = len(group)
        variety_criteria = features_to_check.copy()

        if total_samples < 30:
            area_min = max(50, group['area_px'].quantile(0.01))
            area_max = group['area_px'].quantile(0.99) * 3.0
            variety_criteria['area_px'] = (area_min, area_max)
            ar_min = max(0.05, group['aspect_ratio'].quantile(0.05))
            ar_max = group['aspect_ratio'].quantile(0.99) * 2.5
            variety_criteria['aspect_ratio'] = (ar_min, ar_max)
            if 'convex_compactness' in group.columns:
                cc_min = max(0.3, group['convex_compactness'].quantile(0.05))
                variety_criteria['convex_compactness'] = (cc_min, None)

        elif total_samples < 50:
            area_min = max(80, group['area_px'].quantile(0.05))
            area_max = group['area_px'].quantile(0.95) * 2.0
            variety_criteria['area_px'] = (area_min, area_max)
            ar_min = max(0.1, group['aspect_ratio'].quantile(0.10))
            ar_max = group['aspect_ratio'].quantile(0.98) * 2.0
            variety_criteria['aspect_ratio'] = (ar_min, ar_max)

        elif 'UK' in variety:
            ar_min = max(0.1, group['aspect_ratio'].quantile(0.20))
            ar_max = group['aspect_ratio'].quantile(0.99) * 2.0
            area_min = max(100, group['area_px'].quantile(0.05))
            area_max = group['area_px'].quantile(0.95) * 1.8
            variety_criteria['area_px'] = (area_min, area_max)
            variety_criteria['aspect_ratio'] = (ar_min, ar_max)

        else:
            ar_min = max(0.2, group['aspect_ratio'].quantile(0.40))
            ar_max = group['aspect_ratio'].quantile(0.98) * 1.8
            area_min = max(100, group['area_px'].quantile(0.05))
            area_max = group['area_px'].quantile(0.95) * 1.5
            variety_criteria['area_px'] = (area_min, area_max)
            variety_criteria['aspect_ratio'] = (ar_min, ar_max)

        variety_outliers = []
        for feature, (min_val, max_val) in variety_criteria.items():
            if feature not in group.columns:
                continue

            if min_val is not None and max_val is not None:
                outliers = group[(group[feature] < min_val) | (group[feature] > max_val)]
                cond = f"{feature} < {min_val:.2f} or > {max_val:.2f}"
            elif min_val is not None:
                outliers = group[group[feature] < min_val]
                cond = f"{feature} < {min_val:.2f}"
            elif max_val is not None:
                outliers = group[group[feature] > max_val]
                cond = f"{feature} > {max_val:.2f}"
            else:
                continue

            if len(outliers) > 0:
                stats['threshold_outliers'][feature] = stats['threshold_outliers'].get(feature, 0) + len(outliers)
                outliers_with_reason = outliers.copy()
                outliers_with_reason['outlier_reason'] = f"{feature}: {cond}"
                variety_outliers.append(outliers_with_reason)

        if variety_outliers:
            variety_all_outliers = pd.concat(variety_outliers).drop_duplicates()
            all_outliers.append(variety_all_outliers)
            filtered_df = filtered_df.drop(variety_all_outliers.index)

    outliers_df = pd.concat(all_outliers) if all_outliers else pd.DataFrame()

    stats['filtered'] = len(outliers_df)
    stats['remaining'] = len(filtered_df)
    stats['percent_filtered'] = (stats['filtered'] / stats['total']) * 100 if stats['total'] > 0 else 0

    return filtered_df, outliers_df, stats


def filter_by_quality_score(df, threshold=None, by_variety=True, min_group_size=5):
    """Filter masks by composite quality score.

    Uses variety-specific quantile thresholds when by_variety=True.
    UK varieties use a more lenient 15th percentile; others use the 25th.

    Args:
        df: DataFrame with 'quality_score' and 'variety' columns.
        threshold: Fixed threshold (overrides dynamic if provided).
        by_variety: Use per-variety dynamic thresholds.
        min_group_size: Minimum samples to apply filtering.

    Returns:
        (filtered_df, outliers_df, stats_dict)
    """
    if threshold is None and by_variety:
        thresholds = {}
        for variety, group in df.groupby('variety'):
            if len(group) < min_group_size:
                thresholds[variety] = -np.inf
            elif 'UK' in variety:
                thresholds[variety] = group['quality_score'].quantile(0.15)
            else:
                thresholds[variety] = group['quality_score'].quantile(0.25)

        threshold = df['variety'].map(thresholds)
        mask = df['quality_score'] < threshold
    else:
        threshold = threshold or 0.4
        mask = df['quality_score'] < threshold

    filtered_df = df[~mask].copy()
    outliers_df = df[mask].copy()

    if by_variety:
        outliers_df['outlier_reason'] = outliers_df.apply(
            lambda row: f"quality_score: {row['quality_score']:.3f}", axis=1)
    else:
        outliers_df['outlier_reason'] = outliers_df.apply(
            lambda row: f"quality_score: {threshold:.3f} > {row['quality_score']:.3f}", axis=1)

    stats = {
        'total': len(df),
        'filtered': len(outliers_df),
        'remaining': len(filtered_df),
        'percent_filtered': (len(outliers_df) / len(df)) * 100 if len(df) > 0 else 0
    }

    return filtered_df, outliers_df, stats


def detect_sky_background(mask, original_image=None, mask_position=None):
    """Detect whether a mask contains blue or white sky background.

    Uses BGR color statistics and optionally HSV analysis to identify
    sky-like regions. Position information (mask in upper part of image)
    is used as an additional signal.

    Args:
        mask: Mask image (BGR format for reading).
        original_image: Original image (BGR, optional).
        mask_position: (y, x, h, w) bounding box of mask in original image.

    Returns:
        True if sky background is detected.
    """
    try:
        position_score = 0
        if mask_position is not None and original_image is not None:
            y, x, h, w = mask_position
            img_height = original_image.shape[0]
            center_y_ratio = (y + h / 2) / img_height
            if center_y_ratio < 0.3:
                position_score += 0.4
            elif center_y_ratio < 0.5:
                position_score += 0.2

        if original_image is not None:
            mask_gray = cv2.cvtColor(mask, cv2.COLOR_BGR2GRAY)
            _, mask_binary = cv2.threshold(mask_gray, 1, 255, cv2.THRESH_BINARY)
            if original_image.shape[:2] != mask_binary.shape:
                mask_binary = cv2.resize(mask_binary,
                                         (original_image.shape[1], original_image.shape[0]))
            mask_bool = mask_binary > 0
            roi_pixels = original_image[mask_bool]
        else:
            mask_gray = cv2.cvtColor(mask, cv2.COLOR_BGR2GRAY)
            mask_bool = mask_gray > 0
            roi_pixels = mask[mask_bool]

        if len(roi_pixels) == 0:
            return False

        if len(roi_pixels) > 1000:
            indices = np.random.choice(len(roi_pixels), 1000, replace=False)
            roi_pixels = roi_pixels[indices]

        roi_bgr = roi_pixels.reshape(-1, 3).astype(np.uint8)
        bgr_mean = np.mean(roi_bgr, axis=0)
        bgr_std = np.std(roi_bgr, axis=0)

        blue_score = bgr_mean[0] - (bgr_mean[1] + bgr_mean[2]) / 2
        blue_sky_score = 0
        if (blue_score > 25 and bgr_mean[0] > 100 and
                bgr_mean[1] < 110 and bgr_mean[2] < 100 and bgr_std[0] < 50):
            blue_sky_score = 0.7
        elif (blue_score > 15 and bgr_mean[0] > 80 and
              bgr_mean[1] < 120 and bgr_mean[2] < 110 and bgr_std[0] < 60):
            blue_sky_score = 0.4

        brightness = np.mean(bgr_mean)
        color_variance = np.var(bgr_mean)
        overall_std = np.mean(bgr_std)
        white_sky_score = 0
        if brightness > 180 and color_variance < 80 and overall_std < 40:
            white_sky_score = 0.7
        elif brightness > 160 and color_variance < 120 and overall_std < 50:
            white_sky_score = 0.4

        hsv_sky_score = 0
        if blue_sky_score < 0.8 and white_sky_score < 0.8:
            temp_img = roi_bgr.reshape(1, -1, 3)
            roi_hsv = cv2.cvtColor(temp_img, cv2.COLOR_BGR2HSV).reshape(-1, 3)
            hsv_mean = np.mean(roi_hsv, axis=0)
            hsv_std = np.std(roi_hsv, axis=0)
            hue = hsv_mean[0]
            saturation = hsv_mean[1]
            value = hsv_mean[2]
            if (90 <= hue <= 140 and saturation > 50 and value > 100 and hsv_std[0] < 25):
                hsv_sky_score = 0.5

        color_score = max(blue_sky_score, white_sky_score, hsv_sky_score)
        total_score = color_score + position_score

        return total_score > 0.45

    except Exception as e:
        print(f"Sky background detection error: {str(e)}")
        return False


def enhanced_filter_flow(df, mask_dir, image_dir=None, min_group_size=5,
                         iqr_threshold=1.5, enable_color_filter=True):
    """Run the full 4-stage mask quality filtering pipeline.

    Stage 1: Sky background detection (blue/white sky regions)
    Stage 2: Dynamic threshold filtering (variety-adaptive bounds)
    Stage 3: IQR outlier filtering (convex_compactness, aspect_ratio)
    Stage 4: Quality score filtering (composite weighted score)

    Args:
        df: DataFrame with trait data and 'variety' column.
        mask_dir: Path to mask images (for sky background detection).
        image_dir: Path to original images (optional, for sky detection).
        min_group_size: Minimum variety sample count to apply filtering.
        iqr_threshold: IQR multiplier for Stage 3.
        enable_color_filter: Whether to run Stage 1 (sky detection).

    Returns:
        (filtered_df, all_outliers_df, stats_dict)
    """
    df = df.reset_index(drop=True)

    # Stage 1: Sky background
    if enable_color_filter and mask_dir:
        print("\n=== Stage 1: Sky Background Detection ===")
        filtered_1 = df.copy()
        all_outliers_1 = []
        for idx, row in df.iterrows():
            mask_path = os.path.join(mask_dir, row['mask_filename'])
            if not os.path.exists(mask_path):
                continue
            mask = cv2.imread(mask_path)
            if mask is None:
                continue
            orig_img = None
            if image_dir:
                if '_mask_' in row['mask_filename']:
                    orig_name = row['mask_filename'].split('_mask_')[0]
                else:
                    parts = row['mask_filename'].rsplit('_', 2)
                    orig_name = parts[0] if len(parts) >= 3 else row['mask_filename'].split('_')[0]
                for ext in ['.png', '.jpg', '.jpeg']:
                    p = os.path.join(image_dir, orig_name + ext)
                    if os.path.exists(p):
                        orig_img = cv2.imread(p)
                        break
            if detect_sky_background(mask, orig_img):
                outlier_row = row.copy()
                outlier_row['outlier_reason'] = 'sky_background'
                all_outliers_1.append(outlier_row)
        outliers1 = pd.DataFrame(all_outliers_1) if all_outliers_1 else pd.DataFrame()
        if not outliers1.empty:
            filtered_1 = filtered_1[~filtered_1['mask_filename'].isin(
                outliers1['mask_filename'])]
        df_stage1 = filtered_1
    else:
        df_stage1 = df.copy()
        outliers1 = pd.DataFrame()

    # Stage 2: Dynamic threshold
    print("\n=== Stage 2: Dynamic Threshold Filtering ===")
    df_stage2, outliers2, _ = filter_by_threshold(df_stage1)

    # Stage 3: IQR
    print("\n=== Stage 3: IQR Outlier Filtering ===")
    df_stage3, outliers3, _ = filter_by_multiple_features(
        df_stage2.reset_index(drop=True),
        features=['convex_compactness', 'aspect_ratio'],
        threshold=iqr_threshold,
        min_group_size=min_group_size
    )

    # Stage 4: Quality score
    print("\n=== Stage 4: Quality Score Filtering ===")
    df_with_score = calculate_quality_score(df_stage3.reset_index(drop=True))
    df_stage4, outliers4, _ = filter_by_quality_score(
        df_with_score, threshold=None, by_variety=True,
        min_group_size=min_group_size
    )

    # Merge all outliers
    outlier_frames = []
    for o in [outliers1, outliers2, outliers3, outliers4]:
        if not o.empty:
            outlier_frames.append(o.reset_index(drop=True))

    all_outliers = pd.concat(outlier_frames, ignore_index=True) if outlier_frames else pd.DataFrame()

    stats = {
        'total': len(df),
        'filtered': len(all_outliers),
        'remaining': len(df_stage4),
        'percent_filtered': (len(all_outliers) / len(df)) * 100 if len(df) > 0 else 0
    }

    return df_stage4, all_outliers, stats


