def extract_multiscale_lbp_features(mask, original_image):
    """Extract multi-scale LBP texture features.

    Uses uniform and rotation-invariant LBP at radii [1, 2] with [8, 16] neighbors.
    Adapts parameters based on ROI size.

    Args:
        mask: Binary mask image.
        original_image: Original color or grayscale image.

    Returns:
        Dict of LBP features.
    """
    default_features = {
        'lbp_mean': 0.0, 'lbp_std': 0.0, 'lbp_energy': 0.0,
        'lbp_r1_mean': 0.0, 'lbp_r1_std': 0.0, 'lbp_r1_energy': 0.0,
        'lbp_r2_mean': 0.0, 'lbp_r2_std': 0.0, 'lbp_r2_energy': 0.0,
        'lbp_riu2_mean': 0.0, 'lbp_riu2_std': 0.0, 'lbp_riu2_energy': 0.0
    }

    if mask is None or original_image is None:
        return default_features

    if len(original_image.shape) == 3:
        gray_image = cv2.cvtColor(original_image, cv2.COLOR_BGR2GRAY)
    else:
        gray_image = original_image.copy()

    mask_bool = mask > 0
    roi = np.zeros_like(gray_image)
    roi[mask_bool] = gray_image[mask_bool]

    if np.sum(mask_bool) == 0:
        return default_features

    features = default_features.copy()

    try:
        rows, cols = np.where(mask_bool)
        if len(rows) == 0 or len(cols) == 0:
            return default_features

        height = np.max(rows) - np.min(rows) + 1
        width = np.max(cols) - np.min(cols) + 1

        min_row, max_row = np.min(rows), np.max(rows)
        min_col, max_col = np.min(cols), np.max(cols)
        roi_cropped = roi[min_row:max_row + 1, min_col:max_col + 1]
        mask_cropped = mask_bool[min_row:max_row + 1, min_col:max_col + 1]

        roi_blurred = cv2.GaussianBlur(roi_cropped, (3, 3), 0)

        # Rotation-invariant uniform LBP (P=8, R=1)
        try:
            radius = 1
            n_points = 8
            try:
                lbp_riu2 = local_binary_pattern(roi_blurred, n_points, radius, method='ror')
            except ValueError:
                lbp_riu2 = local_binary_pattern(roi_blurred, n_points, radius, method='uniform')

            lbp_riu2_values = lbp_riu2[mask_cropped]
            if len(lbp_riu2_values) > 0:
                features['lbp_riu2_mean'] = np.mean(lbp_riu2_values)
                features['lbp_riu2_std'] = np.std(lbp_riu2_values)
                features['lbp_riu2_energy'] = np.sum(lbp_riu2_values**2) / len(lbp_riu2_values)
        except Exception:
            pass

        # Multi-scale LBP adapted to ROI size
        if min(height, width) < 30:
            # Very small target: single scale
            radius, n_points = 1, 8
            lbp = local_binary_pattern(roi_blurred, n_points, radius, method='uniform')
            lbp_values = lbp[mask_cropped]

            if len(lbp_values) > 0:
                features['lbp_mean'] = np.mean(lbp_values)
                features['lbp_std'] = np.std(lbp_values)
                features['lbp_energy'] = np.sum(lbp_values**2) / len(lbp_values)
                features['lbp_r1_mean'] = features['lbp_mean']
                features['lbp_r1_std'] = features['lbp_std']
                features['lbp_r1_energy'] = features['lbp_energy']
        else:
            for radius, n_points in [(1, 8), (2, 16)]:
                lbp = local_binary_pattern(roi_blurred, n_points, radius, method='uniform')
                lbp_values = lbp[mask_cropped]

                if len(lbp_values) > 0:
                    prefix = f'lbp_r{radius}'
                    features[f'{prefix}_mean'] = np.mean(lbp_values)
                    features[f'{prefix}_std'] = np.std(lbp_values)
                    features[f'{prefix}_energy'] = np.sum(lbp_values**2) / len(lbp_values)

                    if radius == 1:
                        features['lbp_mean'] = features[f'{prefix}_mean']
                        features['lbp_std'] = features[f'{prefix}_std']
                        features['lbp_energy'] = features[f'{prefix}_energy']

        return features

    except Exception as e:
        print(f"LBP feature extraction error: {str(e)}")
        return default_features


