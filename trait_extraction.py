def calculate_convex_hull_compactness(mask):
    """Compute convex hull compactness (mask_area / hull_area).

    Args:
        mask: Binary mask image.

    Returns:
        (compactness, info_dict) or None.
    """
    contours, _ = cv2.findContours(mask.copy(), cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        return None

    largest_contour = max(contours, key=cv2.contourArea)
    original_area = cv2.contourArea(largest_contour)
    hull = cv2.convexHull(largest_contour)
    hull_area = cv2.contourArea(hull)

    compactness = original_area / hull_area if hull_area > 0 else 0

    return compactness, {
        'original_area': original_area,
        'hull_area': hull_area,
        'hull': hull
    }


def calculate_ellipse_compactness(mask):
    """Compute ellipse compactness (mask_area / ellipse_area).

    Args:
        mask: Binary mask image.

    Returns:
        (compactness, info_dict) or None.
    """
    contours, _ = cv2.findContours(mask.copy(), cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        return None

    largest_contour = max(contours, key=cv2.contourArea)
    original_area = cv2.contourArea(largest_contour)

    if len(largest_contour) >= 5:
        ellipse = cv2.fitEllipse(largest_contour)
        center, axes, angle = ellipse
        a, b = axes[0] / 2, axes[1] / 2
        ellipse_area = np.pi * a * b

        compactness = original_area / ellipse_area if ellipse_area > 0 else 0

        return compactness, {
            'original_area': original_area,
            'ellipse_area': ellipse_area,
            'ellipse': ellipse
        }

    return None


