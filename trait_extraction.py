def batch_extract_all_traits(mask_folder, original_image_folder, output_csv=None,
                             start_index=0, sample_limit=None, args=None):
    """Batch extract traits from all mask-image pairs in the given folders.

    Mask filenames are expected to follow the pattern: <original_name>_mask_<N>.png
    The corresponding original image is looked up as <original_name>.<ext>.

    Args:
        mask_folder: Path to folder containing mask images.
        original_image_folder: Path to folder containing original images.
        output_csv: Output CSV path. If None, results are not saved to disk.
        start_index: Index of first mask file to process.
        sample_limit: Maximum number of masks to process (None = all).
        args: Optional namespace with attributes:
              enable_memory_optimization (bool), max_image_size (int),
              batch_save_interval (int).

    Returns:
        pd.DataFrame with extracted traits, or None on failure.
    """
    if not os.path.exists(mask_folder):
        print(f"Error: Mask folder does not exist: {mask_folder}")
        return None

    if not os.path.exists(original_image_folder):
        print(f"Error: Image folder does not exist: {original_image_folder}")
        return None

    mask_files = sorted([f for f in os.listdir(mask_folder)
                         if f.endswith(('.png', '.jpg', '.jpeg', '.tif'))])

    print(f"Found {len(mask_files)} mask files")

    if start_index > 0 and start_index < len(mask_files):
        mask_files = mask_files[start_index:]

    if sample_limit is not None and sample_limit > 0:
        mask_files = mask_files[:sample_limit]

    if not mask_files:
        print("Error: No mask files to process")
        return None

    results = []
    failed_masks = []
    processed_originals = set()
    start_time = time.time()
    save_interval = getattr(args, 'batch_save_interval', 50) if args else 50
    enable_mem_opt = getattr(args, 'enable_memory_optimization', False) if args else False
    max_img_size = getattr(args, 'max_image_size', 1500) if args else 1500

    try:
        for i, mask_file in enumerate(tqdm(mask_files, desc="Extracting traits")):
            try:
                match = re.search(r'(.+)_mask_\d+\.\w+$', mask_file)
                if not match:
                    print(f"  Warning: Cannot parse original image name from {mask_file}")
                    failed_masks.append(mask_file)
                    continue

                original_basename = match.group(1)

                original_filename = None
                for ext in ['.jpg', '.jpeg', '.png', '.tif', '.bmp']:
                    temp_path = os.path.join(original_image_folder,
                                             original_basename + ext)
                    if os.path.exists(temp_path):
                        original_filename = original_basename + ext
                        break

                if original_filename is None:
                    print(f"  Warning: No matching original image for {mask_file}")
                    failed_masks.append(mask_file)
                    continue

                processed_originals.add(original_filename)

                mask_path = os.path.join(mask_folder, mask_file)
                original_path = os.path.join(original_image_folder, original_filename)

                mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
                original_image = cv2.imread(original_path)

                if mask is None:
                    print(f"  Warning: Cannot read mask {mask_file}")
                    failed_masks.append(mask_file)
                    continue

                if original_image is None:
                    print(f"  Warning: Cannot read image {original_filename}")
                    failed_masks.append(mask_file)
                    continue

                if mask.shape[:2] != original_image.shape[:2]:
                    mask = cv2.resize(mask,
                                      (original_image.shape[1], original_image.shape[0]))

                if enable_mem_opt:
                    original_image, mask, _ = optimize_image_size(
                        original_image, mask, max_img_size)
                    if i % 10 == 0:
                        gc.collect()

                traits = extract_all_wheat_traits(mask, original_image)

                if traits:
                    traits['mask_filename'] = mask_file
                    traits['original_filename'] = original_filename
                    traits['processed_time'] = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
                    results.append(traits)
                else:
                    failed_masks.append(mask_file)

                # Save intermediate results
                if output_csv and i > 0 and (i % save_interval == 0 or i == len(mask_files) - 1):
                    temp_df = pd.DataFrame(results)
                    temp_df.set_index('mask_filename', inplace=True)
                    temp_df = temp_df.dropna(how='all').fillna(0)
                    temp_csv = f"{os.path.splitext(output_csv)[0]}_temp_{i+1}.csv"
                    temp_df.to_csv(temp_csv, na_rep='0')

            except Exception as e:
                print(f"  Error processing {mask_file}: {str(e)}")
                failed_masks.append(mask_file)
                traceback.print_exc()

        processed_count = len(results)
        if processed_count > 0:
            results_df = pd.DataFrame(results)
            results_df.set_index('mask_filename', inplace=True)
            results_df = results_df.dropna(how='all').fillna(0)

            total_time = time.time() - start_time
            print(f"\nProcessing complete!")
            print(f"Total time: {total_time / 60:.2f} min")
            print(f"Speed: {processed_count / total_time:.2f} images/sec")
            print(f"Success: {processed_count}/{len(mask_files)}")
            print(f"Failed: {len(failed_masks)}/{len(mask_files)}")

            if output_csv:
                output_dir = os.path.dirname(output_csv)
                if output_dir and not os.path.exists(output_dir):
                    os.makedirs(output_dir, exist_ok=True)
                results_df.to_csv(output_csv, na_rep='0')
                print(f"Results saved to: {output_csv}")

            return results_df
        else:
            print("Warning: No images were successfully processed")
            return None

    except KeyboardInterrupt:
        print("\nProcessing interrupted by user")
        if results and output_csv:
            results_df = pd.DataFrame(results)
            results_df.set_index('mask_filename', inplace=True)
            results_df = results_df.dropna(how='all').fillna(0)
            interrupted_csv = f"{os.path.splitext(output_csv)[0]}_interrupted.csv"
            results_df.to_csv(interrupted_csv, na_rep='0')
            print(f"Partial results saved to: {interrupted_csv}")
        return None


