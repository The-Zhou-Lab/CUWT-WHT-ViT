def aspect_ratio_pca(mask):
    """Compute aspect ratio using PCA on mask pixel coordinates.

    Args:
        mask: Binary mask image.

    Returns:
        (aspect_ratio, axes_info_dict) or None if too few points.
        axes_info_dict contains: mean, eigenvectors, axis_length,
        main_axis (endpoints), minor_axis (endpoints).
    """
    points = np.where(mask > 0)
    points = np.column_stack((points[1], points[0]))  # (x, y) order

    if len(points) < 3:
        return None

    mean = np.mean(points, axis=0)
    cov = np.cov(points.T)
    eigenvalues, eigenvectors = np.linalg.eig(cov)

    sort_indices = np.argsort(eigenvalues)[::-1]
    eigenvalues = eigenvalues[sort_indices]
    eigenvectors = eigenvectors[:, sort_indices]

    axis_length = 4 * np.sqrt(eigenvalues)  # 4-sigma covers ~95% of points

    aspect_ratio = axis_length[0] / axis_length[1] if axis_length[1] > 0 else float('inf')

    main_axis_endpoint1 = mean + eigenvectors[:, 0] * axis_length[0] / 2
    main_axis_endpoint2 = mean - eigenvectors[:, 0] * axis_length[0] / 2
    minor_axis_endpoint1 = mean + eigenvectors[:, 1] * axis_length[1] / 2
    minor_axis_endpoint2 = mean - eigenvectors[:, 1] * axis_length[1] / 2

    axes_info = {
        'mean': mean,
        'eigenvectors': eigenvectors,
        'axis_length': axis_length,
        'main_axis': (main_axis_endpoint1, main_axis_endpoint2),
        'minor_axis': (minor_axis_endpoint1, minor_axis_endpoint2)
    }

    return aspect_ratio, axes_info


def aspect_ratio_ellipse(mask):
    """Compute aspect ratio using minimum enclosing ellipse fit.

    Args:
        mask: Binary mask image.

    Returns:
        (aspect_ratio, info_dict) or None if contour too small.
        info_dict contains: ellipse parameters, IoU with mask.
    """
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)
    if len(contours) == 0:
        return None

    contour = max(contours, key=cv2.contourArea)
    if len(contour) < 5:
        return None

    ellipse = cv2.fitEllipse(contour)
    (x, y), (width, height), angle = ellipse

    length = max(width, height)
    width = min(width, height)
    aspect_ratio = length / width if width > 0 else float('inf')

    # Evaluate fit quality via IoU
    ellipse_mask = np.zeros_like(mask)
    cv2.ellipse(ellipse_mask, ellipse, 255, -1)
    intersection = np.logical_and(mask > 0, ellipse_mask > 0).sum()
    union = np.logical_or(mask > 0, ellipse_mask > 0).sum()
    iou = intersection / union if union > 0 else 0

    return aspect_ratio, {'ellipse': ellipse, 'iou': iou}


def aspect_ratio_combined(mask, weights=None):
    """Compute aspect ratio by combining PCA and ellipse methods with
    adaptive weighting based on ellipse fit quality.

    Args:
        mask: Binary mask image.
        weights: Optional dict with 'pca' and 'ellipse' weights.

    Returns:
        (combined_ratio, info_dict) or None.
    """
    if weights is None:
        weights = {'pca': 0.5, 'ellipse': 0.5}

    results = {}

    pca_result = aspect_ratio_pca(mask)
    if pca_result is not None:
        results['pca'] = pca_result[0]

    ellipse_result = aspect_ratio_ellipse(mask)
    if ellipse_result is not None:
        ellipse_quality = ellipse_result[1]['iou']
        results['ellipse'] = ellipse_result[0]
        if ellipse_quality > 0.85:
            weights['ellipse'] = min(0.7, weights['ellipse'] * 1.5)
            weights['pca'] = 1.0 - weights['ellipse']
        elif ellipse_quality < 0.4:
            weights['ellipse'] = max(0.3, weights['ellipse'] * 0.8)
            weights['pca'] = 1.0 - weights['ellipse']

    weighted_sum = 0
    total_weight = 0
    for method, value in results.items():
        if method in weights:
            weighted_sum += value * weights[method]
            total_weight += weights[method]

    if total_weight > 0:
        combined_ratio = weighted_sum / total_weight
    else:
        return None

    return combined_ratio, {
        'individual_results': results,
        'weights': weights
    }


