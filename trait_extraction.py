def calculate_voronoi_density(mask, original_image, min_distance=5, threshold_abs=0.02):
    """Compute Voronoi tessellation-based spatial density analysis.

    Detects local intensity peaks within the mask ROI, builds a Voronoi
    diagram, and computes area statistics.

    Args:
        mask: Binary mask image.
        original_image: Original color or grayscale image.
        min_distance: Minimum distance for peak detection.
        threshold_abs: Absolute threshold for peak detection.

    Returns:
        Dict with voronoi_mean_area, voronoi_std_area, voronoi_density,
        voronoi_points_count, voronoi_points_per_area.
    """
    default_features = {
        'voronoi_mean_area': 0.0, 'voronoi_std_area': 0.0,
        'voronoi_density': 0.0, 'voronoi_points_count': 0,
        'voronoi_points_per_area': 0.0
    }

    if mask is None or original_image is None:
        return default_features

    if len(original_image.shape) == 3:
        gray_image = cv2.cvtColor(original_image, cv2.COLOR_BGR2GRAY)
    else:
        gray_image = original_image.copy()

    mask_bool = mask > 0
    roi = np.zeros_like(gray_image)
    roi[mask_bool] = gray_image[mask_bool]

    if np.sum(mask_bool) == 0:
        return default_features

    try:
        rows, cols = np.where(mask_bool)
        if len(rows) == 0 or len(cols) == 0:
            return default_features

        min_row, max_row = np.min(rows), np.max(rows)
        min_col, max_col = np.min(cols), np.max(cols)
        roi_cropped = roi[min_row:max_row + 1, min_col:max_col + 1]
        mask_cropped = mask_bool[min_row:max_row + 1, min_col:max_col + 1]

        roi_enhanced = cv2.equalizeHist(roi_cropped)
        roi_blurred = cv2.GaussianBlur(roi_enhanced, (3, 3), 0)

        height, width = roi_cropped.shape
        if min(height, width) < 30:
            adjusted_min_distance, adjusted_threshold = 3, 0.01
        elif min(height, width) < 60:
            adjusted_min_distance, adjusted_threshold = 4, 0.015
        else:
            adjusted_min_distance, adjusted_threshold = min_distance, threshold_abs

        coordinates = peak_local_max(roi_blurred,
                                     min_distance=adjusted_min_distance,
                                     threshold_abs=adjusted_threshold)

        if len(coordinates) < 3:
            coordinates = peak_local_max(roi_blurred,
                                         min_distance=2, threshold_abs=0.005)

        if len(coordinates) < 3:
            return default_features

        roi_area = np.sum(mask_cropped)
        vor = Voronoi(coordinates)

        areas = []
        for region_idx in vor.point_region:
            region = vor.regions[region_idx]
            if -1 not in region and len(region) > 0:
                polygon = [vor.vertices[i] for i in region]
                if len(polygon) >= 3:
                    area = 0
                    for i in range(len(polygon)):
                        j = (i + 1) % len(polygon)
                        area += polygon[i][0] * polygon[j][1]
                        area -= polygon[j][0] * polygon[i][1]
                    area = abs(area) / 2
                    areas.append(area)

        if len(areas) == 0:
            return default_features

        mean_area = np.mean(areas)
        std_area = np.std(areas)
        points_per_area = len(coordinates) / roi_area if roi_area > 0 else 0
        voronoi_density = 1.0 / mean_area if mean_area > 0 else 0

        features = default_features.copy()
        features.update({
            'voronoi_mean_area': mean_area,
            'voronoi_std_area': std_area,
            'voronoi_density': voronoi_density,
            'voronoi_points_count': len(coordinates),
            'voronoi_points_per_area': points_per_area
        })
        return features

    except Exception as e:
        print(f"Voronoi density error: {str(e)}")
        return default_features


