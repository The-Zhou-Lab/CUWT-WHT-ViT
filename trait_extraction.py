def extract_all_wheat_traits(mask, original_image):
    """Extract all wheat spike traits from a single mask-image pair.

    This is the main entry point for trait extraction. It orchestrates all
    sub-extraction functions and returns a unified dictionary of 50+ features.

    Args:
        mask: Binary mask image (uint8). Can be grayscale or color (will be
              converted to single channel). Values > 0 are treated as foreground.
        original_image: Original color image (BGR) or grayscale image.

    Returns:
        Dict with all extracted features, or None if inputs are invalid.

    Feature categories:
        Shape:    aspect_ratio, area_px
        Compact:  convex_compactness, ellipse_compactness
        Color:    color_r_mean, color_g_mean, color_b_mean, color_r_std, color_g_std,
                  color_b_std, color_lab_l_mean, color_lab_a_mean, color_lab_b_mean,
                  color_lab_l_std, color_lab_a_std, color_lab_b_std, color_h_mean,
                  color_s_mean, color_v_mean, color_h_std, color_red_ratio,
                  color_white_ratio, color_amber_ratio
        GLCM:     glcm_contrast, glcm_homogeneity, glcm_dissimilarity,
                  glcm_correlation, glcm_energy, glcm_asm, glcm_entropy
        LBP:      lbp_mean, lbp_std, lbp_energy, lbp_r1_mean, lbp_r1_std,
                  lbp_r1_energy, lbp_r2_mean, lbp_r2_std, lbp_r2_energy,
                  lbp_riu2_mean, lbp_riu2_std, lbp_riu2_energy
        Voronoi:  voronoi_mean_area, voronoi_std_area, voronoi_density,
                  voronoi_points_count, voronoi_points_per_area
        Spikelet: spikelet_count, spikelet_density, dominant_frequency,
                  estimated_spikelet_count
    """
    if mask is None or original_image is None:
        return None

    if isinstance(mask, np.ndarray) and mask.dtype != np.uint8:
        mask = mask.astype(np.uint8)

    if len(mask.shape) == 3:
        mask = cv2.cvtColor(mask, cv2.COLOR_BGR2GRAY)

    _, mask_binary = cv2.threshold(mask, 1, 255, cv2.THRESH_BINARY)
    mask_smooth = smooth_wheat_mask(mask_binary)

    all_features = {}

    # 1. Aspect ratio (shape)
    ar_result = aspect_ratio_combined(mask_smooth)
    all_features['aspect_ratio'] = ar_result[0] if ar_result is not None else 0

    # 2. Compactness (shape regularity)
    convex_result = calculate_convex_hull_compactness(mask_smooth)
    all_features['convex_compactness'] = convex_result[0] if convex_result is not None else 0

    ellipse_result = calculate_ellipse_compactness(mask_smooth)
    all_features['ellipse_compactness'] = ellipse_result[0] if ellipse_result is not None else 0

    # 3. Color features
    color_features = extract_color_features(mask_smooth, original_image)
    if color_features is not None:
        all_features.update(color_features)

    # 4. GLCM texture features
    glcm_features = extract_glcm_features_advanced(mask_smooth, original_image)
    if glcm_features is not None:
        all_features.update(glcm_features)

    # 5. LBP texture features
    lbp_features = extract_multiscale_lbp_features(mask_smooth, original_image)
    if lbp_features is not None:
        all_features.update(lbp_features)

    # 6. Voronoi density features
    voronoi_features = calculate_voronoi_density(mask_smooth, original_image)
    if voronoi_features is not None:
        all_features.update(voronoi_features)

    # 7. Spikelet count (peak detection)
    spikelet_features = estimate_spikelet_count_peaks(mask_smooth, original_image)
    if spikelet_features is not None:
        all_features.update(spikelet_features)

    # 8. Spikelet density (FFT frequency analysis)
    freq_features = estimate_spikelet_density_frequency(mask_smooth, original_image)
    if freq_features is not None:
        all_features.update(freq_features)

    # 9. Area
    all_features['area_px'] = np.sum(mask_smooth > 0)

    return all_features


