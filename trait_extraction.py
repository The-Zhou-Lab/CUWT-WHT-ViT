def main():
    parser = argparse.ArgumentParser(
        description='Wheat Spike Trait Extraction Pipeline',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Single image extraction
  %(prog)s --single-mask mask.png --single-image image.png

  # Batch extraction
  %(prog)s --mask-folder masks/ --image-folder images/ --output-csv traits.csv

  # With memory optimization
  %(prog)s --mask-folder masks/ --image-folder images/ --output-csv traits.csv --enable-memory-optimization
        """
    )

    # Single image mode
    parser.add_argument('--single-mask', type=str, default=None,
                        help='Path to a single mask image for debugging/testing')
    parser.add_argument('--single-image', type=str, default=None,
                        help='Path to the corresponding original image')

    # Batch mode
    parser.add_argument('--mask-folder', type=str, default=None,
                        help='Folder containing mask images')
    parser.add_argument('--image-folder', type=str, default=None,
                        help='Folder containing original images')
    parser.add_argument('--output-csv', type=str, default=None,
                        help='Output CSV path for batch results')

    # Processing options
    parser.add_argument('--start-index', type=int, default=0,
                        help='Start processing from this index (default: 0)')
    parser.add_argument('--sample-limit', type=int, default=None,
                        help='Maximum number of samples to process')
    parser.add_argument('--enable-memory-optimization', action='store_true',
                        help='Enable image downsampling for large images')
    parser.add_argument('--max-image-size', type=int, default=1500,
                        help='Max image dimension before downsampling (default: 1500)')
    parser.add_argument('--batch-save-interval', type=int, default=50,
                        help='Save intermediate results every N samples (default: 50)')

    # Debug options
    parser.add_argument('--feature-type', choices=['all', 'shape', 'texture', 'density'],
                        default='all', help='Show only specific feature type in debug mode')

    args = parser.parse_args()

    # Single image debug mode
    if args.single_mask and args.single_image:
        print("=== Single Image Debug Mode ===")

        mask = cv2.imread(args.single_mask, cv2.IMREAD_GRAYSCALE)
        image = cv2.imread(args.single_image)

        if mask is None or image is None:
            print("Error: Cannot read mask or image file")
            return

        if mask.shape[:2] != image.shape[:2]:
            print("Warning: Resizing mask to match image dimensions")
            mask = cv2.resize(mask, (image.shape[1], image.shape[0]))

        if args.enable_memory_optimization:
            image, mask, scale = optimize_image_size(image, mask, args.max_image_size)
            if scale < 1.0:
                print(f"Image scaled by factor {scale:.3f}")

        features = extract_all_wheat_traits(mask, image)

        print("\nExtracted features:")
        if args.feature_type != 'all':
            type_filters = {
                'shape': ['aspect', 'compact', 'area', 'perimeter'],
                'texture': ['glcm', 'lbp'],
                'density': ['spikelet', 'voronoi']
            }
            keywords = type_filters.get(args.feature_type, [])
            for k, v in features.items():
                if any(kw in k for kw in keywords):
                    print(f"  {k}: {v}")
        else:
            for k, v in features.items():
                print(f"  {k}: {v}")
        return

    # Batch mode
    if args.mask_folder and args.image_folder:
        print("=== Batch Processing Mode ===")

        if args.enable_memory_optimization:
            print(f"Memory optimization enabled (max size: {args.max_image_size}px)")

        batch_extract_all_traits(
            args.mask_folder,
            args.image_folder,
            args.output_csv,
            args.start_index,
            args.sample_limit,
            args
        )
        return

    parser.print_help()


if __name__ == "__main__":
    main()
