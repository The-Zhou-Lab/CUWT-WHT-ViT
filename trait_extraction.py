def smooth_wheat_mask(mask, quality_check=True):
    """Smooth a wheat spike mask by keeping the largest connected component
    and optionally applying morphological operations.

    Args:
        mask: Binary mask image (uint8, 0/255).
        quality_check: If True, only apply morphological smoothing when
                       contour complexity exceeds a threshold.

    Returns:
        Smoothed binary mask (uint8, 0/255).
    """
    result = mask.copy()

    # Keep only the largest connected component
    mask_bool = (result > 0)
    num_labels, labels, stats_arr, centroids = cv2.connectedComponentsWithStats(
        mask_bool.astype(np.uint8), connectivity=8)

    if num_labels > 1:
        max_label = 1
        max_area = stats_arr[1, cv2.CC_STAT_AREA]
        for j in range(2, num_labels):
            area = stats_arr[j, cv2.CC_STAT_AREA]
            if area > max_area:
                max_area = area
                max_label = j
        result = (labels == max_label).astype(np.uint8) * 255
    else:
        if num_labels <= 1:
            return np.zeros_like(mask_bool, dtype=np.uint8)

    contours, _ = cv2.findContours(result, cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)
    if len(contours) == 0:
        return result

    main_contour = max(contours, key=cv2.contourArea)
    perimeter = cv2.arcLength(main_contour, True)
    area = cv2.contourArea(main_contour)
    complexity = perimeter**2 / (4 * np.pi * area) if area > 0 else float('inf')

    if not quality_check or complexity > 1.5:
        kernel_open = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
        result = cv2.morphologyEx(result, cv2.MORPH_OPEN, kernel_open)

        kernel_close = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))
        result = cv2.morphologyEx(result, cv2.MORPH_CLOSE, kernel_close)

        result = cv2.GaussianBlur(result, (5, 5), 0)
        _, result = cv2.threshold(result, 127, 255, cv2.THRESH_BINARY)

    return result


