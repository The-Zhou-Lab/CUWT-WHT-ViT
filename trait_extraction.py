def extract_glcm_features_advanced(mask, original_image):
    """Extract GLCM texture features along the PCA-aligned main axis.

    Computes 7 features at multiple distances [1, 3, 5]:
    contrast, homogeneity, dissimilarity, correlation, energy, ASM, entropy.

    Args:
        mask: Binary mask image.
        original_image: Original color or grayscale image.

    Returns:
        Dict of GLCM features, or None on failure.
    """
    if len(original_image.shape) == 3:
        gray_image = cv2.cvtColor(original_image, cv2.COLOR_BGR2GRAY)
    else:
        gray_image = original_image.copy()

    mask_bool = mask > 0
    roi = np.zeros_like(gray_image)
    roi[mask_bool] = gray_image[mask_bool]

    if np.sum(mask_bool) == 0:
        return None

    # Determine PCA-aligned angle for GLCM
    pca_result = aspect_ratio_pca(mask)
    if pca_result is None:
        angles = [0]
    else:
        _, axes_info = pca_result
        eigenvectors = axes_info['eigenvectors']
        main_axis_vector = eigenvectors[:, 0]
        angle_rad = np.arctan2(main_axis_vector[1], main_axis_vector[0])
        angle_deg = np.degrees(angle_rad)

        std_angles = [0, 45, 90, 135]
        main_angle = angle_deg % 180
        closest_angle_idx = np.argmin(
            [abs((main_angle - ang) % 180) for ang in std_angles])
        main_glcm_angle = std_angles[closest_angle_idx]
        angles = [np.radians(main_glcm_angle)]

    rows, cols = np.where(mask_bool)
    if len(rows) == 0 or len(cols) == 0:
        return None

    min_row, max_row = np.min(rows), np.max(rows)
    min_col, max_col = np.min(cols), np.max(cols)

    roi_cropped = roi[min_row:max_row + 1, min_col:max_col + 1]
    mask_cropped = mask_bool[min_row:max_row + 1, min_col:max_col + 1]

    if roi_cropped.max() > 0:
        roi_normalized = ((roi_cropped / roi_cropped.max()) * 255).astype(np.uint8)
    else:
        return None

    distances = [1, 3, 5]
    levels = 256
    symmetric = True
    normed = True

    features = {}

    try:
        roi_masked = roi_normalized.copy()
        roi_masked[~mask_cropped] = 0

        glcm = graycomatrix(roi_masked, distances=distances, angles=angles,
                            levels=levels, symmetric=symmetric, normed=normed)

        properties = ['contrast', 'homogeneity', 'dissimilarity',
                      'correlation', 'energy']
        for prop in properties:
            try:
                value = graycoprops(glcm, prop).mean()
                features[f'glcm_{prop}'] = value
            except Exception:
                features[f'glcm_{prop}'] = 0

        # ASM = energy^2
        try:
            features['glcm_asm'] = features.get('glcm_energy', 0) ** 2
        except Exception:
            features['glcm_asm'] = 0

        # Entropy (not provided by graycoprops)
        try:
            entropy_val = 0
            for i in range(glcm.shape[0]):
                for j in range(glcm.shape[1]):
                    for a in range(glcm.shape[2]):
                        for d in range(glcm.shape[3]):
                            if glcm[i, j, a, d] > 0:
                                entropy_val -= glcm[i, j, a, d] * np.log2(glcm[i, j, a, d])
            features['glcm_entropy'] = entropy_val / (glcm.shape[2] * glcm.shape[3])
        except Exception:
            features['glcm_entropy'] = 0

        return features
    except Exception as e:
        print(f"GLCM computation error: {str(e)}")
        return None


