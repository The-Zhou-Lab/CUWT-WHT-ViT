def estimate_spikelet_count_peaks(mask, original_image):
    """Estimate spikelet count by detecting peaks in the intensity profile
    along the PCA main axis.

    Args:
        mask: Binary mask image.
        original_image: Original color or grayscale image.

    Returns:
        Dict with spikelet_count, spikelet_density.
    """
    if len(original_image.shape) == 3:
        gray_image = cv2.cvtColor(original_image, cv2.COLOR_BGR2GRAY)
    else:
        gray_image = original_image.copy()

    mask_bool = mask > 0
    roi = np.zeros_like(gray_image)
    roi[mask_bool] = gray_image[mask_bool]

    if np.sum(mask_bool) == 0:
        return {'spikelet_count': 0, 'spikelet_density': 0}

    try:
        coords = np.column_stack(np.where(mask_bool))
        if len(coords) < 2:
            return {'spikelet_count': 0, 'spikelet_density': 0}

        mean = np.mean(coords, axis=0)
        coords_centered = coords - mean
        cov = np.cov(coords_centered.T)
        eigenvalues, eigenvectors = np.linalg.eig(cov)

        idx = np.argmax(eigenvalues)
        main_axis = eigenvectors[:, idx]
        projected = np.dot(coords_centered, main_axis)

        sort_idx = np.argsort(projected)
        coords_sorted = coords[sort_idx]

        intensity_profile = []
        for coord in coords_sorted:
            x, y = coord
            if 0 <= x < roi.shape[0] and 0 <= y < roi.shape[1]:
                intensity_profile.append(roi[x, y])

        if not intensity_profile or len(intensity_profile) < 3:
            return {'spikelet_count': 0, 'spikelet_density': 0}

        intensity_profile = np.array(intensity_profile)
        window_length = min(5, len(intensity_profile) -
                            (1 if len(intensity_profile) % 2 == 0 else 0))
        if window_length >= 3:
            intensity_profile = savgol_filter(intensity_profile, window_length, 2)

        peaks, _ = find_peaks(intensity_profile, distance=5)
        spikelet_count = len(peaks)

        axis_length = np.max(projected) - np.min(projected)
        spikelet_density = spikelet_count / axis_length if axis_length > 0 else 0

        return {
            'spikelet_count': spikelet_count,
            'spikelet_density': spikelet_density
        }
    except Exception as e:
        print(f"Spikelet detection error: {str(e)}")
        return {'spikelet_count': 0, 'spikelet_density': 0}


def estimate_spikelet_density_frequency(mask, original_image):
    """Estimate spikelet density using FFT-based frequency analysis of the
    intensity profile along the PCA main axis.

    Args:
        mask: Binary mask image.
        original_image: Original color or grayscale image.

    Returns:
        Dict with dominant_frequency, estimated_spikelet_count, spikelet_density.
    """
    if len(original_image.shape) == 3:
        gray_image = cv2.cvtColor(original_image, cv2.COLOR_BGR2GRAY)
    else:
        gray_image = original_image.copy()

    mask_bool = mask > 0
    roi = np.zeros_like(gray_image)
    roi[mask_bool] = gray_image[mask_bool]

    if np.sum(mask_bool) == 0:
        return {'dominant_frequency': 0, 'estimated_spikelet_count': 0, 'spikelet_density': 0}

    try:
        coords = np.column_stack(np.where(mask_bool))
        if len(coords) < 2:
            return {'dominant_frequency': 0, 'estimated_spikelet_count': 0, 'spikelet_density': 0}

        mean = np.mean(coords, axis=0)
        coords_centered = coords - mean
        cov = np.cov(coords_centered.T)
        eigenvalues, eigenvectors = np.linalg.eig(cov)

        idx = np.argmax(eigenvalues)
        main_axis = eigenvectors[:, idx]
        projected = np.dot(coords_centered, main_axis)

        sort_idx = np.argsort(projected)
        coords_sorted = coords[sort_idx]

        intensity_profile = []
        for coord in coords_sorted:
            x, y = coord
            if 0 <= x < roi.shape[0] and 0 <= y < roi.shape[1]:
                intensity_profile.append(roi[x, y])

        if len(intensity_profile) < 10:
            return {'dominant_frequency': 0, 'estimated_spikelet_count': 0, 'spikelet_density': 0}

        intensity_profile = np.array(intensity_profile)
        window_length = min(11, len(intensity_profile) -
                            (1 if len(intensity_profile) % 2 == 0 else 0))
        if window_length >= 3:
            intensity_profile = savgol_filter(intensity_profile, window_length, 2)

        fft_result = fft(intensity_profile)
        fft_magnitude = np.abs(fft_result)

        n = len(fft_magnitude) // 2
        if n <= 1:
            return {'dominant_frequency': 0, 'estimated_spikelet_count': 0, 'spikelet_density': 0}

        fft_magnitude = fft_magnitude[1:n]  # skip DC component

        peak_idx = np.argmax(fft_magnitude)
        dominant_frequency = (peak_idx + 1) / len(intensity_profile)
        estimated_spikelet_count = dominant_frequency * len(intensity_profile)

        axis_length = np.max(projected) - np.min(projected)
        spikelet_density = estimated_spikelet_count / axis_length if axis_length > 0 else 0

        return {
            'dominant_frequency': dominant_frequency,
            'estimated_spikelet_count': int(estimated_spikelet_count),
            'spikelet_density': spikelet_density
        }
    except Exception as e:
        print(f"FFT frequency analysis error: {str(e)}")
        return {'dominant_frequency': 0, 'estimated_spikelet_count': 0, 'spikelet_density': 0}


